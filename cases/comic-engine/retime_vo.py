from shots_orig import SHOTS
V='/tmp/claude-0/-home-user-saraya/5ff36b23-2257-528a-8aa2-85aceb2b057c/scratchpad/vo/'
segs=json.load(open(V+'segs.json')); sil=json.load(open(V+'sil.json'))
def trim(a,e):
    for s0,s1 in sil:
        if s0<=a<=s1: a=s1
        if s0<=e<=s1: e=s0
    return a,e
segs=[trim(a,e) for a,e in segs]
MAP=[('souq',.6),('shoes',.8),('knock',.5),('knock',4.3),('tape',.6),('watch_open',3.8),('title',.5),('office',.8),
     ('casefile',.6),('khalil_door',1.0),('stairs',.6),('discovery',2.0),('watch',.5),('safe',.5),('redledger',.5),
     ('tea',.5),('ashtray',.5),('ledger',.5),('bag',.5),('tape2',.5),('farag',.9),('khalil_int',.9),('zainab',.9),
     ('mustafa',.9),('suleiman',.9),('eyes',2.5),('tapefinal',.5),('board',.8),('question',.3),('end',.5)]
assert len(MAP)==len(segs)==30
GAP=0.25
out=[]; place=[]  # place: (shot_index, new_offset, seg_a, seg_e)
for si,sh in enumerate(SHOTS):
    sh=copy.deepcopy(sh); parts=[(o,segs[k]) for k,(sid,o) in enumerate(MAP) if sid==sh['id']]
    narr_kinds=('cap','em','tag')
    items=[]
    for (o,(a,e)) in parts: items.append((o,0,'N',(a,e)))
    for j,el in enumerate(sh.get('els',[])):
        if el[1] in narr_kinds and parts: continue
        items.append((el[0],1,'E',j))
    for j,x in enumerate(sh.get('sfx',[])): items.append((x[0],1,'S',j))
    for j,x in enumerate(sh.get('aud',[])): items.append((x[0],1,'A',j))
    for j,x in enumerate(sh.get('shake',[])): items.append((x,1,'K',j))
    for j,x in enumerate(sh.get('flash',[])): items.append((x,1,'F',j))
    for j,x in enumerate(sh.get('title',[])): items.append((x[0],1,'T',j))
    items.sort(key=lambda z:(z[0],z[1]))
    S=0; busy=0; shifts=[(0,0)]; nparts=[]
    for (t,_,kind,ref) in items:
        nt=t+S
        if kind=='N':
            if nt<busy: S+=busy-nt; nt=busy
            a,e=ref; nparts.append((nt,e-a,a,e)); busy=nt+(e-a)+GAP
        else:
            if kind=='E': blocking=SHOTS[si]['els'][ref][1] in('say','tape')
            else: blocking=(SHOTS[si]['id']=='knock' and kind in('S','A','K'))
            if blocking and nt<busy and nt>=(nparts[-1][0] if nparts else 0): S+=busy-nt; nt=busy
        shifts.append((t,S))
    def mp(t):
        s=0
        for (tt,ss) in shifts:
            if tt<=t: s=ss
        return t+s
    # remap
    if 'els' in sh:
        els=[]; caps=[(j,el) for j,el in enumerate(sh['els']) if el[1] in narr_kinds]
        has_head=any(el[1] in('tag','card') for el in sh['els'])
        for j,el in enumerate(sh['els']):
            el=list(el)
            if el[1] in narr_kinds and nparts:
                # which part: last part whose original offset <= caption time (+0.3)
                pi=0
                for k,(o,_) in enumerate(parts):
                    if o<=el[0]+0.3: pi=k
                st,ln,_,_=nparts[pi]
                mine=[c for c in caps if c[1][1]!='tag' and (max([k for k,(o,_) in enumerate(parts) if o<=c[1][0]+0.3] or [0])==pi)]
                if el[1]=='tag': el[0]=max(0.2,st-0.1)
                else:
                    tot=sum(len(c[1][2]) for c in mine); before=sum(len(c[1][2]) for c in mine if c[0]<j)
                    f0=0.18 if has_head else 0.0
                    el[0]=st+0.05+ln*(f0+(1-f0)*before/max(tot,1))*0.92
            else: el[0]=mp(el[0])
            els.append(tuple(el))
        sh['els']=els
    if 'sfx' in sh: sh['sfx']=[tuple([mp(x[0])]+list(x[1:])) for x in sh['sfx']]
    if 'aud' in sh: sh['aud']=[(mp(x[0]),x[1],x[2]) for x in sh['aud']]
    if 'shake' in sh: sh['shake']=[mp(x) for x in sh['shake']]
    if 'flash' in sh: sh['flash']=[mp(x) for x in sh['flash']]
    if 'title' in sh: sh['title']=[tuple([mp(x[0])]+list(x[1:])) for x in sh['title']]
    if 'amb' in sh:
        sh['amb']={k:((mp(v[0]),mp(v[1])) if isinstance(v,tuple) else v) for k,v in sh['amb'].items()}
    end_need=max([p[0]+p[1]+0.7 for p in nparts]+[0])
    sh['dur']=round(max(sh['dur']+S,end_need),2)
    for p in nparts: place.append((si,p[0],p[2],p[3]))
    out.append(sh)
