/** يحدد نوع التأثير من اسم الهدية، وإن لم يُعرف فمن قيمتها بالعملات */
export function giftKind(name = '', coins = 0) {
  const n = String(name).toLowerCase();
  for (const [kind, def] of Object.entries(GIFT_KINDS)) {
    if (def.match.some((m) => n.includes(m))) return kind;
  }
  if (coins >= 500) return 'grand';
  if (coins >= 99) return 'meteor';
  return 'sparkle';
}

